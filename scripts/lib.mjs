const TEXT_EXT = new Set(['.md', '.txt', '.json', '.yaml', '.yml', '.toml', '.py', '.js', '.mjs', '.ts', '.sh', '.ps1', '.html', '.css', '.csv'])

export const abs = (p) => path.join(ROOT, ...p.split('/'))
export const exists = (p) => fs.existsSync(abs(p))
export const isDir = (p) => exists(p) && fs.statSync(abs(p)).isDirectory()
export const normalize = (s) => s.replace(/\r\n/g, '\n')
export const readText = (p) => normalize(fs.readFileSync(abs(p), 'utf8'))
export const isText = (p) => TEXT_EXT.has(path.posix.extname(p).toLowerCase())
export const readAny = (p) => (isText(p) ? readText(p) : fs.readFileSync(abs(p)))

/** Recursively list files under a repo-relative directory as sorted posix paths. */
export function listFiles(dir) {
  const out = []
  const walk = (d) => {
    if (!isDir(d)) return
    for (const entry of fs.readdirSync(abs(d), { withFileTypes: true })) {
      const p = `${d}/${entry.name}`
      if (entry.isDirectory()) walk(p)
      else out.push(p)
    }
  }
  walk(dir)
  return out.sort()
}

export function listDirs(dir) {
  if (!isDir(dir)) return []
  return fs
    .readdirSync(abs(dir), { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort()
}

/** Split `---` YAML frontmatter from a Markdown body. Returns data=null when absent. */
export function parseFrontmatter(text) {
  text = normalize(text)
  const m = /^---\n([\s\S]*?)^---[ \t]*(?:\n|$)/m.exec(text)
  if (!m || m.index !== 0) return { data: null, body: text }
  const data = YAML.parse(m[1]) ?? {}
  return { data, body: text.slice(m[0].length).replace(/^\n+/, '') }
}

export const stringifyYaml = (obj) => YAML.stringify(obj, { lineWidth: 0 })

/** Load every canonical source into one model. Structural load errors go into `errors`. */
export function loadModel() {
  const errors = []
  const err = (file, msg) => errors.push(`${file}: ${msg}`)

  let workflow = {}
  try {
    workflow = YAML.parse(readText('workflow.yaml')) ?? {}
  } catch (e) {
    err('workflow.yaml', `cannot parse: ${e.message}`)
  }

  let lock = {}
  if (exists('skills-lock.json')) {
    try {
      lock = JSON.parse(readText('skills-lock.json')).skills ?? {}
    } catch (e) {
      err('skills-lock.json', `cannot parse: ${e.message}`)
    }
  }

  const loadEntities = (dir) => {
    const map = new Map()
    for (const file of listFiles(dir)) {
      if (!file.endsWith('.md') || file.split('/').length !== 2) continue
      try {
        const { data, body } = parseFrontmatter(readText(file))
        if (!data) {
          err(file, 'missing YAML frontmatter')
          continue
        }
        const name = path.posix.basename(file, '.md')
        map.set(name, { file, name, data, body })
      } catch (e) {
        err(file, `invalid frontmatter: ${e.message}`)
      }
    }
    return map
  }

  const agents = loadEntities('agents')
  const commands = loadEntities('commands')

  const skills = new Map()
  for (const dirName of listDirs('.agents/skills')) {
    const dir = `.agents/skills/${dirName}`
    const file = `${dir}/SKILL.md`
    if (!exists(file)) {
      err(dir, 'missing SKILL.md')
      continue
    }
    const text = readText(file)
    try {
      const { data, body } = parseFrontmatter(text)
      skills.set(dirName, {
        name: dirName,
        dir,
        file,
        data: data ?? {},
        hasFrontmatter: data !== null,
        body,
        generated: text.includes(MARKER),
        thirdParty: Object.hasOwn(lock, dirName),
      })
    } catch (e) {
      err(file, `invalid frontmatter: ${e.message}`)
    }
  }

  return { workflow, lock, agents, commands, skills, errors }
}

// ---- Small accessors with defaults -------------------------------------------------

export const targetsOf = (entity) => entity.data.targets ?? PLATFORMS
export const wants = (entity, platform) => targetsOf(entity).includes(platform)
export const delegatesOf = (agent) => agent.data.delegates ?? []
export const skillsOf = (entity) => entity.data.skills ?? []
export const includesOf = (agent) => agent.data.includes ?? []
export const permissionsOf = (agent) => {
  const p = agent.data.permissions ?? {}
  return { edit: p.edit ?? 'ask', bash: p.bash ?? 'deny', web: p.web ?? 'allow' }
}

/** Agent names an agent may delegate to, expanding "*" to every other agent. */
export function delegationTargets(agent, model) {
  const d = delegatesOf(agent)
  if (d.includes('*')) return [...model.agents.keys()].filter((n) => n !== agent.name)
  return d
}

/** Agents that can delegate to `name`. */
export function callersOf(name, model) {
  return [...model.agents.values()]
    .filter((a) => a.name !== name && (delegatesOf(a).includes('*') || delegatesOf(a).includes(name)))
    .map((a) => a.name)
}

/** Hand-written skills from this repository (not installed third-party, not generated). */
export const firstPartySkills = (model) => [...model.skills.values()].filter((s) => !s.generated && !s.thirdParty)
